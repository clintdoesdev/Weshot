// Generates src/fonts/givonic/generated.ts.
// next/font/local fails the build when a file is missing, so the Givonic slot is only wired up
// once the licensed WOFF2 files have been dropped into src/fonts/givonic/.
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/fonts/givonic');
const weights = [
  { weight: '400', file: 'Givonic-Regular.woff2' },
  { weight: '500', file: 'Givonic-Medium.woff2' },
  { weight: '600', file: 'Givonic-SemiBold.woff2' },
];
const present = weights.filter((w) => existsSync(join(dir, w.file)));
const out = join(dir, 'generated.ts');

const body =
  present.length > 0
    ? `// Generated by scripts/givonic.mjs. Do not edit.
import localFont from 'next/font/local';

export const givonic: { variable: string } | null = localFont({
  src: [
${present.map((w) => `    { path: './${w.file}', weight: '${w.weight}', style: 'normal' },`).join('\n')}
  ],
  variable: '--font-givonic',
  display: 'swap',
  fallback: ['Outfit', 'system-ui', 'sans-serif'],
});
`
    : `// Generated by scripts/givonic.mjs. Do not edit.
// No Givonic WOFF2 files found in this folder, so Outfit carries the design.
export const givonic: { variable: string } | null = null;
`;

writeFileSync(out, body);
console.log(present.length > 0 ? `Givonic: using ${present.length} WOFF2 file(s)` : 'Givonic: files not found, using Outfit');
